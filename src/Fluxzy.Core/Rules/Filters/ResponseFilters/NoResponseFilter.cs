using System;
using System.Collections.Generic;
using Fluxzy.Core;
using Fluxzy.Misc;

namespace Fluxzy.Rules.Filters.ResponseFilters
{
    /// <summary>
    ///     Select exchanges for which the remote never answered: no response header was received
    ///     and fluxzy did not produce an error on its own. This is a view filter, it never matches
    ///     an exchange still being processed by the proxy pipeline.
    /// </summary>
    [FilterMetaData(
        LongDescription = "Select exchanges that received no response from the remote (request sent, " +
                          "connection closed or proxy stopped before any response header arrived). " +
                          "Exchanges failed by fluxzy itself (528, DNS or connection errors) are excluded."
    )]
    public class NoResponseFilter : Filter
    {
        public override Guid Identifier => (GetType().Name + Inverted).GetMd5Guid();

        public override FilterScope FilterScope => FilterScope.OutOfScope;

        public override string AutoGeneratedName => "No response received";

        public override string GenericName => "No response";

        public override string ShortName => "noresp.";

        public override bool PreMadeFilter => true;

        protected override bool InternalApply(
            ExchangeContext? exchangeContext, IAuthority authority, IExchange? exchange,
            IFilteringContext? filteringContext)
        {
            if (exchange == null)
                return false;

            if (exchange is Exchange)
                return false;

            return exchange.StatusCode == 0 && exchange.ClientErrors.Count == 0;
        }

        public override IEnumerable<FilterExample> GetExamples()
        {
            var defaultSample = GetDefaultSample();

            if (defaultSample != null)
                yield return defaultSample;
        }
    }
}
